/**
 * Builds public/qrscore/*.css from the original qrscore stylesheets in design/qrscore-src/.
 * Every selector is scoped under `.qrs`, so the old site's global rules (body, h1, button, .btn, .wrap ...) can only affect markup that sits
 * inside a `.qrs` wrapper and never leak into the Tailwind pages around it.
 *
 *   node scripts/qrs-css.mjs
 */
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const SRC = path.resolve("design/qrscore-src");
const OUT = path.resolve("public/qrscore");
const ROOTS = /^(:root|html|body)\b/;

function scope(selector) {
  return selector.split(",").map((s) => {
    const t = s.trim();
    if (t === "*" || t === "*, *::before, *::after") return ".qrs *";
    if (t.startsWith("*")) return `.qrs ${t}`;
    if (ROOTS.test(t)) return t.replace(ROOTS, ".qrs");
    return `.qrs ${t}`;
  }).join(", ");
}

for (const file of fs.readdirSync(SRC).filter((f) => f.endsWith(".css"))) {
  if (file === "shell.css") { fs.copyFileSync(path.join(SRC, file), path.join(OUT, file)); console.log(`copied ${file}`); continue; }
  const root = postcss.parse(fs.readFileSync(path.join(SRC, file), "utf8"));
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;
    rule.selector = scope(rule.selector);
  });
  fs.writeFileSync(path.join(OUT, file), `/* Generated by scripts/qrs-css.mjs from design/qrscore-src/${file}. Do not edit. */\n${root.toString()}`);
  console.log(`scoped ${file}`);
}
