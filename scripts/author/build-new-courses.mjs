/**
 * Build the interactive courses written in scripts/author/courses/*.mjs.
 *   node scripts/author/build-new-courses.mjs
 * For every source it writes:
 *   lib/market/data/lessons/<slug>.json      the lessons, quizzes and capstone
 *   lib/learn/data/<slug>.activities.json    the interactive labs, skills, badges and landing page
 * and it updates the catalogue entry (honest hours, outline) in lib/market/data/courses.json and the two lazy registries
 * (lib/market/new-lessons.ts, lib/learn/new-activities.ts). Solutions never leave the source files: they are used only by the tests.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "../..");
const dir = path.join(import.meta.dirname, "courses");

export async function loadSources() {
  const files = readdirSync(dir).filter((f) => f.endsWith(".mjs")).sort();
  const out = [];
  for (const f of files) out.push((await import(pathToFileURL(path.join(dir, f)).href)).default);
  return out;
}

export const stable = (o) => JSON.stringify(o);

async function main() {
  const built = await loadSources();
  const catPath = path.join(root, "lib/market/data/courses.json");
  const cat = JSON.parse(readFileSync(catPath, "utf8"));
  const slugs = [];
  for (const c of built) {
    writeFileSync(path.join(root, "lib/market/data", "lessons", `${c.slug}.json`), stable(c.lesson));
    writeFileSync(path.join(root, "lib/learn/data", `${c.slug}.activities.json`), stable(c.activities));
    const row = cat.courses.find((x) => x.slug === c.slug);
    if (!row) throw new Error(`${c.slug} is not in the catalogue`);
    Object.assign(row, c.catalogue, { modules: c.lesson.modules.length });
    slugs.push(c.slug);
    console.log(c.slug.padEnd(40), c.lesson.modules.length, "modules", c.lesson.modules.reduce((a, m) => a + m.topics.length, 0), "lessons", c.activities.activities.length, "labs");
  }
  writeFileSync(catPath, JSON.stringify(cat, null, 2) + "\n");
  const req = (folder, suffix) => slugs.map((s) => `  ${JSON.stringify(s)}: () => require(${JSON.stringify(`./data/${folder}${s}${suffix}`)}),`).join("\n");
  writeFileSync(path.join(root, "lib/market/new-lessons.ts"),
    `/* Generated by scripts/author/build-new-courses.mjs. Do not edit. Loaded on first use so the lesson files are not read for pages that only list courses. */\n/* eslint-disable @typescript-eslint/no-require-imports */\nexport const NEW_LESSONS: Record<string, () => unknown> = {\n${req("lessons/", ".json")}\n};\n`);
  writeFileSync(path.join(root, "lib/learn/new-activities.ts"),
    `/* Generated by scripts/author/build-new-courses.mjs. Do not edit. */\n/* eslint-disable @typescript-eslint/no-require-imports */\nexport const NEW_ACTIVITIES: Record<string, () => unknown> = {\n${slugs.map((s) => `  ${JSON.stringify(s)}: () => require(${JSON.stringify(`./data/${s}.activities.json`)}),`).join("\n")}\n};\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await main();
