-- 0015_booking_intents.sql
-- Cal.com booking pipeline, part 1 of 2. STRICTLY ADDITIVE: one new table,
-- no changes to any existing table, column, constraint, policy or function.
--
-- WHY THIS TABLE EXISTS
--
-- cal.com is an off-site page. The moment a visitor leaves growqr.ai for the
-- booking form, every piece of first-touch attribution we hold — the UTM
-- snapshot in sessionStorage (lib/attribution.ts), the page they clicked from,
-- the modal's solution/agent context, the server-derived country — is gone.
-- The webhook that comes back from Cal knows only what Cal itself collected:
-- name, email, time, and any booking-question answers.
--
-- So we hand the visitor an opaque token on the way out and keep the context
-- here. CalButton generates a uuid client-side, fires this row off with
-- sendBeacon, and appends ?intent=<uuid> to the Cal URL, where it lands in a
-- hidden booking question. The webhook reads the uuid back out of the payload
-- and rejoins the two halves.
--
-- The id is CLIENT-generated on purpose: it means the button never has to wait
-- for a server round-trip before opening the booking tab, which is what keeps
-- Safari from treating window.open() as a non-user-gesture popup and blocking
-- it. The beacon is fire-and-forget; if it never lands, the booking still
-- works and the attribution columns simply stay NULL — the same graceful
-- degradation bot_leads already relies on (see lib/crm/payload.ts, which
-- resolves Lead_Source="Website" when attribution is absent).
--
-- Rows are write-once/read-once and worthless after a few weeks. The crm-sync
-- cron purges them at 30 days.

create table if not exists public.booking_intents (
  -- Generated by crypto.randomUUID() in the browser; the default is a safety
  -- net for any server-side caller, never the normal path.
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz not null default now(),

  -- Which surface the visitor clicked. A CLOSED vocabulary, enforced here as
  -- well as in TypeScript and zod: free-text sources become unusable analytics
  -- within a couple of months, and the constraint is what makes that
  -- impossible rather than merely discouraged. Adding a surface = one migration
  -- line + one entry in BOOKING_SOURCES (lib/cal.ts). The two must stay in step.
  source        text not null,

  -- Where the click happened. Drives Audience/Business_Unit/Product_Interest
  -- via solutionFromPath() — the SAME function the bot uses, never a second
  -- mapping table. Distinct from landing_page below, which is first-touch:
  -- someone can land on /ai-brand-builder from an ad and book from
  -- /enterprise-solutions, and both facts matter.
  page_path     text,

  -- Enterprise-modal context, when the click came from one.
  solution      text,
  agent         text,

  -- Server truth (x-vercel-ip-country), never spoofable form data — same
  -- precedence rule as lib/forms/handler.ts countryFromRequest().
  country_code  text,

  -- First-touch attribution snapshot, verbatim. Nothing derived, nothing
  -- bucketed (feedback_crm_no_inferred_values).
  utm_source    text,
  utm_medium    text,
  utm_campaign  text,
  utm_term      text,
  utm_content   text,
  gclid         text,
  landing_page  text,
  referrer      text,

  -- Stamped when a webhook claims this intent. Purely observational: it makes
  -- "clicked but never booked" measurable, and a second booking reusing a
  -- shared link visible.
  consumed_at   timestamptz
);

alter table public.booking_intents
  drop constraint if exists booking_intents_source_check;

alter table public.booking_intents
  add constraint booking_intents_source_check
  check (source = any (array[
    'b2b-enterprise-modal',   -- EnterpriseContactModal (both placements)
    'enterprise-hero',        -- EnterpriseSolutionsPage hero CTA
    'enterprise-final-cta',   -- EnterpriseSolutionsPage closing CTA
    'brand-intelligence',     -- BrandIntelligenceSection walkthrough CTA
    'persona-cta',            -- lib/persona-content.ts secondary CTA
    'seeker-waitlist-modal'   -- SeekerWaitlistModal (B2C — locked decision D1)
  ]));

-- The 30-day purge scans by age.
create index if not exists booking_intents_created_at_idx
  on public.booking_intents (created_at);

-- Service-role writes only, matching every other lead table. No public
-- policies: the intent endpoint runs server-side with the admin client.
alter table public.booking_intents enable row level security;

comment on table public.booking_intents is
  'Attribution bridge for Cal.com bookings: carries UTM/page/solution context across the off-site hop. Written by /api/cal/intent, read once by /api/cal/webhook, purged at 30 days.';
comment on column public.booking_intents.source is
  'Closed vocabulary — must stay in step with BOOKING_SOURCES in lib/cal.ts.';
comment on column public.booking_intents.page_path is
  'Page the booking click happened on (drives Audience). Distinct from landing_page, which is first-touch.';
